// El texto queda como respaldo para los puentes anteriores.
export const FOODLY_FOOTER_MARKER = '\x1f';

export function isFoodlyFooterLine(line: string): boolean {
  if (!line.startsWith(FOODLY_FOOTER_MARKER)) return false;
  const text = line.slice(1).trimStart();
  return text === FOODLY_FOOTER_TEXT || text === 'Foodly';
}
