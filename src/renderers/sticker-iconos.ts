export interface IconoArte {
  ancho: number;
  alto: number;
  puntos: boolean[];
}

function desdeArte(filas: string[]): IconoArte {
  return {
    ancho: filas[0].length,
    alto: filas.length,
    puntos: filas.join('').split('').map(c => c === '#'),
  };
}

